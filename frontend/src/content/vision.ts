export const visionDictionaries: Record<Lang, Dict> = { en, hi, ne };

export function visionText(lang: Lang, key: VisionKey, vars?: Record<string, string | number>): string {
  const raw = visionDictionaries[lang]?.[key] ?? en[key];
  return vars ? raw.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : raw;
}

export function useVisionText() {
  const { lang } = useI18n();
  return useCallback((key: VisionKey, vars?: Record<string, string | number>) => visionText(lang, key, vars), [lang]);
}
