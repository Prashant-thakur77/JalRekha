export const dictionaries: Record<Lang, Dict> = { en, hi, ne };

/** Native names for message languages (alerts can be in more languages than the UI). */
export const MESSAGE_LANG_NAMES: Record<string, string> = {
  en: 'English',
  hi: 'हिन्दी',
  ne: 'नेपाली',
  mai: 'मैथिली',
  bho: 'भोजपुरी',
};

export function messageLangName(code: string): string {
  return MESSAGE_LANG_NAMES[code] ?? code;
}

export type Vars = Record<string, string | number>;

export function translate(lang: Lang, key: MsgKey, vars?: Vars): string {
  const template = dictionaries[lang]?.[key] ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

/** Translate a key that is only known at runtime (e.g. `mode.${mode}`); falls back to `fallback`. */
export function translateDynamic(lang: Lang, key: string, fallback: string): string {
  if (key in en) return translate(lang, key as MsgKey);
  return fallback;
}

const STORAGE_KEY = 'nadisaathi.lang';

function isLang(value: unknown): value is Lang {
  return value === 'en' || value === 'hi' || value === 'ne';
}

function readStoredLang(): Lang {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (isLang(stored)) return stored;
  } catch {
    // storage blocked (private mode, sandboxed iframe): fall back to English
  }
  return 'en';
}

function applyDocumentLang(lang: Lang) {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang;
  }
}

interface LangState {
  lang: Lang;
  setLang: (lang: Lang) => void;
}

const initialLang = typeof window === 'undefined' ? 'en' : readStoredLang();
applyDocumentLang(initialLang);

export const useLangStore = create<LangState>((set) => ({
  lang: initialLang,
  setLang: (lang) => {
    try {
      window.localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      // ignore: the choice still applies for this session
    }
    applyDocumentLang(lang);
    set({ lang });
  },
}));

export function useI18n() {
  const lang = useLangStore((s) => s.lang);
  const setLang = useLangStore((s) => s.setLang);
  const t = useCallback((key: MsgKey, vars?: Vars) => translate(lang, key, vars), [lang]);
  const td = useCallback(
    (key: string, fallback: string) => translateDynamic(lang, key, fallback),
    [lang],
  );
  return { lang, setLang, t, td };
}
