"""Export the submission traces: runs the three scenario replays headless and writes
the cycles where an OpenCV output changed the agent's next action.

    cd backend && uv run python ../scripts/export_traces.py

Output: docs/traces/<scenario>.jsonl (every cycle) and docs/traces/README.md
(the cycles with a decision, one line each, linking OpenCV number -> next action).
"""

from __future__ import annotations

import json
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
os.environ.setdefault("JALREKHA_DATA_DIR", tempfile.mkdtemp(prefix="traces-"))
os.environ["NADISAATHI_AWS_ENABLED"] = "0"
os.environ["NADISAATHI_TTS_ENABLED"] = "0"
sys.path.insert(0, str(ROOT / "backend" / "src"))

from sqlmodel import Session  # noqa: E402

from jalrekha.agent import runner, scenarios  # noqa: E402
from jalrekha.db.database import edge_engine, init_db  # noqa: E402

OUT = ROOT / "docs" / "traces"


def main() -> int:
    init_db()
    OUT.mkdir(parents=True, exist_ok=True)
    lines = ["# Agent traces (SCENARIO REPLAY)", "",
             "Generated by `scripts/export_traces.py`: procedural camera frames, the real OpenCV pipeline, the real agent. "
             "Bedrock is off in this export, so D3 shows the fallback path; D7 uses an injected adversarial VLM reply (labelled in the trace). "
             "Each line: simulated time, the OpenCV number that triggered the branch, and the action before → after.", ""]
    for sid in scenarios.SCENARIOS:
        rec = scenarios.run_scenario(sid, delay_s=0)
        with Session(edge_engine) as s:
            rows = scenarios.latest_trace_rows(s, rec["run_id"])
        path = OUT / f"{sid}.jsonl"
        with path.open("w") as fh:
            for r in rows:
                t = runner.trace_to_api(r)
                for st in t["steps"]:
                    st["t"] = None  # wall-clock times are noise in a committed file
                fh.write(json.dumps(t, ensure_ascii=False) + "\n")
        lines += [f"## {scenarios.SCENARIOS[sid].title}", "", f"`{path.relative_to(ROOT)}`: {len(rows)} cycles.", ""]
        for r in rows:
            t = runner.trace_to_api(r)
            m = t["measurement"]
            for st in t["steps"]:
                d = st.get("decision")
                if not d or not d.get("branch"):
                    continue
                stage = m.get("stage_m")
                lines.append(f"- {t['started_at'][11:16]} `{d['branch']}` {st['tool']}: {d['reason']} "
                             f"(camera {stage if stage is None else f'{stage:.2f} m'}, truth {m.get('truth_stage_m')} m) "
                             f"→ {json.dumps(d.get('before'), ensure_ascii=False)} → {json.dumps(d.get('after'), ensure_ascii=False)} "
                             f"[{t['trace_id']}#{st['i']}]")
        lines.append("")
    (OUT / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
