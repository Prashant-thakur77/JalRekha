#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BACKEND_DIR="$ROOT_DIR/backend"
HOST="${JALREKHA_API_HOST:-0.0.0.0}"
PORT="${JALREKHA_API_PORT:-8000}"

export JALREKHA_NODE_PROFILE="${JALREKHA_NODE_PROFILE:-raspberry-pi-16gb-multimodal-prod}"
export JALREKHA_DATA_DIR="${JALREKHA_DATA_DIR:-/mnt/jalrekha/data}"
export JALREKHA_NODE_PROVIDER="${JALREKHA_NODE_PROVIDER:-litert}"
export JALREKHA_NODE_MODEL_PATH="${JALREKHA_NODE_MODEL_PATH:-$BACKEND_DIR/data/models/gemma-4-E2B-it.litertlm}"
export JALREKHA_NODE_BACKEND="${JALREKHA_NODE_BACKEND:-gpu}"
export JALREKHA_NODE_MULTIMODAL_BACKEND="${JALREKHA_NODE_MULTIMODAL_BACKEND:-cpu}"
export JALREKHA_NODE_MULTIMODAL_VISION_BACKEND="${JALREKHA_NODE_MULTIMODAL_VISION_BACKEND:-cpu}"
export JALREKHA_NODE_CACHE_DIR="${JALREKHA_NODE_CACHE_DIR:-$BACKEND_DIR/data/litert-cache}"
export JALREKHA_NODE_ENABLE_SPECULATIVE_DECODING="${JALREKHA_NODE_ENABLE_SPECULATIVE_DECODING:-true}"
export JALREKHA_NODE_MAX_OUTPUT_TOKENS="${JALREKHA_NODE_MAX_OUTPUT_TOKENS:-1024}"
export JALREKHA_NODE_MULTIMODAL_MAX_OUTPUT_TOKENS="${JALREKHA_NODE_MULTIMODAL_MAX_OUTPUT_TOKENS:-2048}"
export JALREKHA_LLM_ENABLED="${JALREKHA_LLM_ENABLED:-false}"
export JALREKHA_LLM_BASE_URL="${JALREKHA_LLM_BASE_URL:-http://127.0.0.1:11434/v1}"
export JALREKHA_LLM_MODEL="${JALREKHA_LLM_MODEL:-gemma4:e2b}"
export JALREKHA_LLM_API_KEY="${JALREKHA_LLM_API_KEY:-ollama}"

export JALREKHA_MULTIMODAL_ENABLED="${JALREKHA_MULTIMODAL_ENABLED:-true}"
export JALREKHA_MULTIMODAL_VERIFIER_ENABLED="${JALREKHA_MULTIMODAL_VERIFIER_ENABLED:-false}"
export JALREKHA_MULTIMODAL_BASE_URL="${JALREKHA_MULTIMODAL_BASE_URL:-$JALREKHA_LLM_BASE_URL}"
export JALREKHA_MULTIMODAL_MODEL="${JALREKHA_MULTIMODAL_MODEL:-gemma-4-E2B-it.litertlm}"
export JALREKHA_MULTIMODAL_MAX_FRAMES="${JALREKHA_MULTIMODAL_MAX_FRAMES:-4}"
export JALREKHA_MULTIMODAL_FRAME_SAMPLE_SECONDS="${JALREKHA_MULTIMODAL_FRAME_SAMPLE_SECONDS:-60}"
export JALREKHA_MULTIMODAL_IMAGE_MAX_SIDE="${JALREKHA_MULTIMODAL_IMAGE_MAX_SIDE:-960}"
export JALREKHA_MULTIMODAL_NUM_CTX="${JALREKHA_MULTIMODAL_NUM_CTX:-4096}"
export JALREKHA_MULTIMODAL_NUM_PREDICT="${JALREKHA_MULTIMODAL_NUM_PREDICT:-512}"
export JALREKHA_MULTIMODAL_TIMEOUT_SECONDS="${JALREKHA_MULTIMODAL_TIMEOUT_SECONDS:-240}"

export JALREKHA_MAX_CURATED_FRAMES="${JALREKHA_MAX_CURATED_FRAMES:-4}"
export JALREKHA_ARTIFACT_RETENTION_DAYS="${JALREKHA_ARTIFACT_RETENTION_DAYS:-14}"

cd "$BACKEND_DIR"
if [[ -d ".venv" ]]; then
  # shellcheck disable=SC1091
  source ".venv/bin/activate"
else
  echo "Missing backend virtualenv at $BACKEND_DIR/.venv" >&2
  exit 1
fi

python3 "$ROOT_DIR/scripts/fetch_litert_model.py"
python3 "$ROOT_DIR/scripts/fetch_demo_assets.py"
PYTHONPATH=src python3 -m jalrekha.scripts.seed
PYTHONPATH=src python3 -m uvicorn jalrekha.main:app --host "$HOST" --port "$PORT"
